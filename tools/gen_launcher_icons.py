"""Generate the per-palette launcher icon resources.

Android cannot retint an icon at runtime, so "the icon follows the theme" means
one activity-alias per palette, each with its own static icon, exactly one of
them enabled. That is a lot of near-identical XML, so it is generated from the
palettes themselves rather than typed out — a palette added to the enum later
only needs this script run again.
"""
import pathlib
import re

APP = pathlib.Path("/home/user/CarTrackingApp/app/src/main")
RES = APP / "res"
SRC = APP / "java/com/agcoding/cartrackingapp"
OUT = pathlib.Path(__file__).parent / "generated"

# The two palettes built from BrandTokens have no primaryDark; their accent is
# primary400 in both themes (see darkScheme in AppColorScheme.kt). SYSTEM takes
# its colours from the wallpaper at runtime, which no static resource can
# follow, so it keeps the default.
DEFAULT_TEAL = "4DB6AC"
FIXED = {
    "SYSTEM": DEFAULT_TEAL,
    "DEFAULT_BLUE": "1976D2",
    "OCEAN_TEAL": "00796B",
}

# Deliberately NOT readableContent()'s 0.22. That crossover is for text, where
# a thin letterform at 12sp needs 4.5:1 to be legible. This is a single large
# graphic with thick strokes: white holds up on everything down to about 2:1,
# which is also what the brand icon does on its teal. Measured across the
# palettes, 0.5 is exactly where white stops reading — above it the accents are
# pastels and golds that swallow a white glyph whole.
LUMINANCE_CROSSOVER = 0.5


def enum_order() -> list[str]:
    text = (SRC / "data/preferences/ColorPalettePreferences.kt").read_text()
    body = text.split("enum class ColorPalette {", 1)[1].split("}", 1)[0]
    names = []
    for line in body.splitlines():
        line = line.split("//")[0].strip().rstrip(",")
        if re.fullmatch(r"[A-Z][A-Z_]*", line):
            names.append(line)
    return names


def palette_objects() -> dict[str, str]:
    """ColorPalette entry -> the Color.kt object that holds its primary."""
    text = (SRC / "presentation/theme/AppTheme.kt").read_text()
    return dict(
        re.findall(r"ColorPalette\.(\w+)\s*->\s*if \(isDark\) (\w+)\.primaryDark", text)
    )


def primaries() -> dict[str, str]:
    """Color.kt object -> its primaryDark hex, without the alpha byte."""
    text = (SRC / "presentation/theme/Color.kt").read_text()
    out = {}
    for obj_name, body in re.findall(
        r"object (\w+Palette) \{(.*?)\n\}", text, re.S
    ):
        m = re.search(r"val primaryDark\s*=\s*Color\(0x[fF]{2}([0-9a-fA-F]{6})\)", body)
        if m:
            out[obj_name] = m.group(1).upper()
    return out


def luminance(hex6: str) -> float:
    def channel(v: int) -> float:
        c = v / 255.0
        return c / 12.92 if c <= 0.03928 else ((c + 0.055) / 1.055) ** 2.4

    r, g, b = (int(hex6[i : i + 2], 16) for i in (0, 2, 4))
    return 0.2126 * channel(r) + 0.7152 * channel(g) + 0.0722 * channel(b)


def pascal(name: str) -> str:
    return "".join(part.capitalize() for part in name.split("_"))


def main() -> None:
    OUT.mkdir(exist_ok=True)
    order = enum_order()
    objects = palette_objects()
    prim = primaries()

    resolved: dict[str, str] = {}
    for entry in order:
        if entry in FIXED:
            resolved[entry] = FIXED[entry]
            continue
        obj = objects.get(entry)
        if obj is None or obj not in prim:
            raise SystemExit(f"no primary found for {entry} (object={obj})")
        resolved[entry] = prim[obj]

    # ---- colours -------------------------------------------------------
    colors = ['<?xml version="1.0" encoding="utf-8"?>', "<!--",
              "  Generated: one launcher-icon background per ColorPalette.",
              "  Each is that palette's accent, so the icon on the home screen",
              "  is the colour the app is painted in.",
              "-->", "<resources>"]
    for entry in order:
        colors.append(
            f'    <color name="ic_launcher_bg_{entry.lower()}">#{resolved[entry]}</color>'
        )
    colors.append("</resources>")
    (RES / "values/ic_launcher_palette_colors.xml").write_text(
        "\n".join(colors) + "\n"
    )

    # ---- adaptive icons ------------------------------------------------
    anydpi = RES / "mipmap-anydpi-v26"
    dark_ink = []
    for entry in order:
        ink_is_dark = luminance(resolved[entry]) > LUMINANCE_CROSSOVER
        if ink_is_dark:
            dark_ink.append(entry)
        foreground = (
            "ic_launcher_cariboo1_foreground_ink"
            if ink_is_dark
            else "ic_launcher_cariboo1_foreground"
        )
        xml = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by gen_aliases.py; see ic_launcher_palette_colors.xml. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_bg_{entry.lower()}"/>
    <foreground android:drawable="@mipmap/{foreground}"/>
    <monochrome android:drawable="@mipmap/ic_launcher_cariboo1_monochrome"/>
</adaptive-icon>
"""
        (anydpi / f"ic_launcher_palette_{entry.lower()}.xml").write_text(xml)

    # ---- manifest aliases ----------------------------------------------
    aliases = []
    for entry in order:
        default = entry == "SYSTEM"
        aliases.append(
            f"""        <activity-alias
            android:name=".LauncherIcon{pascal(entry)}"
            android:targetActivity=".MainActivity"
            android:exported="true"
            android:enabled="{str(default).lower()}"
            android:icon="@mipmap/ic_launcher_palette_{entry.lower()}"
            android:roundIcon="@mipmap/ic_launcher_palette_{entry.lower()}"
            android:label="@string/app_name">
            <intent-filter>
                <action android:name="android.intent.action.MAIN" />
                <category android:name="android.intent.category.LAUNCHER" />
            </intent-filter>
        </activity-alias>"""
        )
    (OUT / "aliases.xml").write_text("\n".join(aliases) + "\n")

    # ---- Kotlin mapping -------------------------------------------------
    cases = "\n".join(
        f"    ColorPalette.{e} -> \"$PACKAGE.LauncherIcon{pascal(e)}\"" for e in order
    )
    (OUT / "mapping.kt.txt").write_text(cases + "\n")

    print(f"{len(order)} palettes")
    print(f"dark ink on {len(dark_ink)}: {', '.join(dark_ink)}")


if __name__ == "__main__":
    main()
